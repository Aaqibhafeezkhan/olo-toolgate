package io.ololabs.toolgate.sdk.processor;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import javax.lang.model.SourceVersion;

/**
 * The typed accessors of java.md: one {@code <HandlerClass>Vars} class per class that holds tools, with
 * {@code global(context)}, {@code secret(context)} and {@code jwt(context)} views whose methods read each declared
 * value with the getter for its type, for example {@code OrderToolsVars.global(context).timeoutSeconds()}.
 */
final class Accessors {
    /** One kind of value: the accessor method, the context method it wraps, its view class and its values by name. */
    record Kind(String accessor, String contextMethod, String viewClass, String valuesType, String what, Map<String, String> values) {}

    private static final Set<String> RESERVED = Set.of("getClass", "hashCode", "toString", "notify", "notifyAll", "wait", "clone",
            "finalize", "equals");

    private Accessors() {}

    /** The name of the accessors class for a handler class, such as {@code OrderToolsVars}. */
    static String className(List<String> enclosingNames) {
        return String.join("", enclosingNames) + "Vars";
    }

    /** The accessor method for a declared name: lower camel case, and never a Java keyword or an Object method. */
    static String method(String name) {
        StringBuilder out = new StringBuilder();
        for (String part : name.split("_+")) {
            if (part.isEmpty()) continue;
            String p = part.equals(part.toUpperCase(Locale.ROOT)) ? part.toLowerCase(Locale.ROOT) : part;
            out.append(out.length() == 0 ? Character.toLowerCase(p.charAt(0)) : Character.toUpperCase(p.charAt(0))).append(p.substring(1));
        }
        String m = out.toString();
        return SourceVersion.isKeyword(m) || RESERVED.contains(m) ? m + "Value" : m;
    }

    /** The return type and body of an accessor for a value type. */
    private static String[] read(String type, String name) {
        String n = "\"" + name + "\"";
        return switch (type) {
            case "INT" -> new String[] {"int", "values.getIntValue(" + n + ")"};
            case "LONG" -> new String[] {"long", "values.getLongValue(" + n + ")"};
            case "NUMBER" -> new String[] {"double", "values.getNumberValue(" + n + ")"};
            case "BOOLEAN" -> new String[] {"boolean", "values.getBooleanValue(" + n + ")"};
            case "DATE" -> new String[] {"java.time.LocalDate", "values.getDateValue(" + n + ")"};
            case "DATE_TIME" -> new String[] {"java.time.OffsetDateTime", "values.getDateTimeValue(" + n + ")"};
            case "DURATION" -> new String[] {"java.time.Duration", "values.getDurationValue(" + n + ")"};
            case "BINARY" -> new String[] {"byte[]", "values.getBinaryValue(" + n + ")"};
            case "OBJECT" -> new String[] {"<T> T", "values.getObjectValue(" + n + ", type)"};
            case "ARRAY" -> new String[] {"<T> java.util.List<T>", "values.getListValue(" + n + ", type)"};
            default -> new String[] {"String", "values.getStringValue(" + n + ")"};
        };
    }

    /** The source of the accessors class, or null when no kind has values. */
    static String source(String packageName, String className, String handlerClass, List<Kind> kinds) {
        if (kinds.stream().allMatch(k -> k.values().isEmpty())) return null;
        StringBuilder s = new StringBuilder();
        if (!packageName.isEmpty()) s.append("package ").append(packageName).append(";\n\n");
        s.append("/** Typed access to the values the tools in {@link ").append(handlerClass).append("} declare. Generated by the ToolGate processor. */\n");
        s.append("@javax.annotation.processing.Generated(\"io.ololabs.toolgate.sdk.processor.DescriptorProcessor\")\n");
        s.append("public final class ").append(className).append(" {\n");
        s.append("    private ").append(className).append("() {}\n");
        for (Kind k : kinds) {
            if (k.values().isEmpty()) continue;
            s.append("\n    /** The ").append(k.what()).append(" of this invocation. */\n");
            s.append("    public static ").append(k.viewClass()).append(' ').append(k.accessor())
                    .append("(io.ololabs.toolgate.sdk.context.ToolContext context) {\n");
            s.append("        return new ").append(k.viewClass()).append("(context.").append(k.contextMethod()).append("());\n    }\n");
            s.append("\n    /** Declared ").append(k.what()).append(", each read with the getter for its type. */\n");
            s.append("    public static final class ").append(k.viewClass()).append(" {\n");
            s.append("        private final ").append(k.valuesType()).append(" values;\n\n");
            s.append("        private ").append(k.viewClass()).append('(').append(k.valuesType()).append(" values) {\n");
            s.append("            this.values = values;\n        }\n");
            for (Map.Entry<String, String> v : new TreeMap<>(k.values()).entrySet()) {
                String[] read = read(v.getValue(), v.getKey());
                boolean typed = read[0].startsWith("<");
                s.append("\n        /** ").append(v.getKey()).append(" (").append(v.getValue()).append("). */\n");
                s.append("        public ").append(read[0]).append(' ').append(method(v.getKey()))
                        .append(typed ? "(Class<T> type)" : "()").append(" {\n");
                s.append("            return ").append(read[1]).append(";\n        }\n");
            }
            s.append("    }\n");
        }
        s.append("}\n");
        return s.toString();
    }

    /** Accessor names must not collide within one view; returns the first collision, or null. */
    static String collision(Map<String, String> values) {
        Map<String, String> seen = new LinkedHashMap<>();
        for (String name : values.keySet()) {
            String prior = seen.put(method(name), name);
            if (prior != null) return prior + " and " + name;
        }
        return null;
    }
}
