"""What a handler sees: ToolContext and the types around it (spec/authoring/python.md).

The runtime supplies the implementations; handlers type their ``context`` parameter as ``ToolContext``.
"""

from __future__ import annotations

import datetime as _dt
import logging
import socket
from typing import Any, Callable, Dict, Generic, List, Mapping, Optional, Protocol, Type, TypeVar

from .enums import InvocationMode

__all__ = [
    "ToolContext", "Values", "Jwt", "HttpClient", "RouteCall", "RawResponse", "TcpConnector", "Invocation",
    "CancellationToken", "InputRequest", "ToolResult",
]

T = TypeVar("T")


class Values(Protocol):
    """Declared values of one kind, read with the getter for their type."""

    def get_str(self, name: str) -> str: ...
    def get_int(self, name: str) -> int: ...
    def get_long(self, name: str) -> int: ...
    def get_number(self, name: str) -> float: ...
    def get_bool(self, name: str) -> bool: ...
    def get_date(self, name: str) -> _dt.date: ...
    def get_datetime(self, name: str) -> _dt.datetime: ...
    def get_duration(self, name: str) -> _dt.timedelta: ...
    def get_object(self, name: str, type: Type[T]) -> T: ...
    def get_list(self, name: str, type: Type[T]) -> List[T]: ...
    def get_bytes(self, name: str) -> bytes: ...


class Jwt(Values, Protocol):
    """Declared claims of the caller's verified identity."""

    @property
    def user_name(self) -> str: ...
    @property
    def subject(self) -> str: ...
    @property
    def issuer(self) -> str: ...


class RawResponse:
    """A route response as received: status, headers (lower-case names) and body bytes."""

    def __init__(self, status: int, headers: Mapping[str, List[str]], body: bytes) -> None:
        self.status = status
        self.headers = {k: list(v) for k, v in headers.items()}
        self.body = body

    def __repr__(self) -> str:
        return "RawResponse(status=%d, %d bytes)" % (self.status, len(self.body))


class RouteCall(Protocol):
    def path_var(self, name: str, value: object) -> "RouteCall": ...
    def query(self, name: str, value: object) -> "RouteCall": ...
    def header(self, name: str, value: str) -> "RouteCall": ...
    def body(self, value: object) -> "RouteCall": ...
    def timeout(self, seconds: float) -> "RouteCall": ...
    def send(self, response_type: Type[T]) -> T: ...
    def send_raw(self) -> RawResponse: ...
    async def send_async(self, response_type: Type[T]) -> T: ...


class HttpClient(Protocol):
    def route(self, route_id: str) -> RouteCall: ...
    def get(self, destination_id: str, path_template: str) -> RouteCall: ...
    def post(self, destination_id: str, path_template: str) -> RouteCall: ...
    def put(self, destination_id: str, path_template: str) -> RouteCall: ...
    def patch(self, destination_id: str, path_template: str) -> RouteCall: ...
    def delete(self, destination_id: str, path_template: str) -> RouteCall: ...
    def head(self, destination_id: str, path_template: str) -> RouteCall: ...


class TcpConnector(Protocol):
    def connect(self, destination_id: str) -> socket.socket: ...


class CancellationToken(Protocol):
    def is_cancellation_requested(self) -> bool: ...
    def throw_if_cancellation_requested(self) -> None: ...
    def on_cancel(self, callback: Callable[[], None]) -> None: ...


class Invocation(Protocol):
    @property
    def invocation_id(self) -> str: ...
    @property
    def tool_id(self) -> str: ...
    @property
    def agent_id(self) -> Optional[str]: ...
    @property
    def user_id(self) -> Optional[str]: ...
    @property
    def catalog_revision(self) -> Optional[int]: ...
    @property
    def deadline(self) -> _dt.datetime: ...
    @property
    def business_key(self) -> Optional[str]: ...
    @property
    def attempt(self) -> int: ...
    @property
    def mode(self) -> InvocationMode: ...


class InputRequest(Generic[T]):
    """A question for the caller: a message, the JSON Schema of the answer, and the type to convert it to."""

    def __init__(self, message: str, requested_schema: Mapping[str, Any], answer_type: Type[T]) -> None:
        self.message = message
        self.requested_schema = dict(requested_schema)
        self.answer_type = answer_type

    @classmethod
    def of(cls, message: str, requested_schema: Mapping[str, Any], answer_type: Type[T]) -> "InputRequest[T]":
        return cls(message, requested_schema, answer_type)


class ToolResult:
    """A result written by hand: MCP content blocks and optional structured content."""

    def __init__(self, content: List[Dict[str, Any]], structured_content: Optional[Dict[str, Any]] = None) -> None:
        self.content = [dict(c) for c in content]
        self.structured_content = None if structured_content is None else dict(structured_content)

    @classmethod
    def of(cls, content: List[Dict[str, Any]], structured_content: Optional[Dict[str, Any]] = None) -> "ToolResult":
        return cls(content, structured_content)

    @classmethod
    def text(cls, text: str) -> "ToolResult":
        return cls([{"type": "text", "text": text}])

    def __repr__(self) -> str:
        return "ToolResult(content=%r, structured_content=%r)" % (self.content, self.structured_content)


class ToolContext(Protocol):
    """The handler's view of one invocation."""

    globals: Values
    secrets: Values
    jwt: Jwt
    http: HttpClient
    tcp: TcpConnector
    invocation: Invocation
    cancellation: CancellationToken
    log: logging.Logger

    def get_str(self, name: str) -> str: ...
    def get_int(self, name: str) -> int: ...
    def get_long(self, name: str) -> int: ...
    def get_number(self, name: str) -> float: ...
    def get_bool(self, name: str) -> bool: ...
    def get_date(self, name: str) -> _dt.date: ...
    def get_datetime(self, name: str) -> _dt.datetime: ...
    def get_duration(self, name: str) -> _dt.timedelta: ...
    def get_object(self, name: str, type: Type[T]) -> T: ...
    def get_list(self, name: str, type: Type[T]) -> List[T]: ...
    def get_bytes(self, name: str) -> bytes: ...
    def progress(self, fraction: float, message: Optional[str] = None) -> None: ...
    def is_cancelled(self) -> bool: ...
    def request_input(self, request: InputRequest[T]) -> T: ...
