"""Descriptor generation: import the tool modules, read their declarations, emit generation-1 descriptors.

``build_project(root)`` is what ``python -m toolgate`` runs; ``build(modules, generation)`` is the core.
The index it writes (``_toolgate_index/package.json`` and ``tools/<name>.json``) is how the runtime finds the
descriptors and handlers inside a packaged tool.
"""

from __future__ import annotations

import os
import types
from pathlib import Path
from typing import List, Optional, Sequence, Tuple

from .problems import BuildFailed, Problem, Site
from .processor import GENERATION, Build, build
from .project import Project, import_modules, load_project

__all__ = ["BuildFailed", "Problem", "Site", "GENERATION", "Build", "build", "Project", "load_project",
           "import_modules", "build_project", "write_index", "INDEX_PACKAGE"]

#: The import package that carries the index inside a staged or packaged tool.
INDEX_PACKAGE = "_toolgate_index"


def build_project(root: Optional[os.PathLike] = None) -> Tuple[Project, List[types.ModuleType], Build]:
    project = load_project(root)
    from .processor import check_generation
    check_generation(project.generation)
    modules = import_modules(project)
    return project, modules, build(modules, project.generation)


def write_index(result: Build, directory: os.PathLike) -> Path:
    """Writes ``<directory>/_toolgate_index``: the package index and one canonical descriptor file per tool."""
    base = Path(directory) / INDEX_PACKAGE
    tools = base / "tools"
    tools.mkdir(parents=True, exist_ok=True)
    for old in tools.glob("*.json"):
        if old.stem not in result.bytes:
            old.unlink()
    (base / "__init__.py").write_text("# Generated by the ToolGate descriptor build.\n", encoding="utf-8")
    (base / "package.json").write_bytes(result.index_bytes)
    for name, data in result.bytes.items():
        (tools / (name + ".json")).write_bytes(data)
    return base
