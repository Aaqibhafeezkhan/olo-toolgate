"""Generates the shared identity fixtures for adapter A4 (tool-sdk/spec/protocol-layer.md A4).

Usage: python3 generate.py   write jwks.json, jwks-rotated.json and tokens.json

Needs the `cryptography` package. Every run makes fresh keys and discards the private halves, so the
output differs between runs and no signing key is ever committed. Tokens use fixed timestamps around
FIXTURE_NOW; verifiers run them with their clock set to tokens.json "now".
"""
import base64
import hashlib
import hmac
import json
from pathlib import Path

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, padding, rsa
from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature

HERE = Path(__file__).resolve().parent
FIXTURE_NOW = 1_790_000_000  # 2026-09-21T13:33:20Z
ISSUER = 'https://issuer.fixtures.toolgate.invalid'
AUDIENCE = 'https://tools.fixtures.toolgate.invalid/mcp'
HEADER = ('# Copyright 2026 OLO Labs; SPDX-License-Identifier: Apache-2.0. Generated by generate.py; '
          'fixture keys whose private halves were discarded.')


def b64(data):
    return base64.urlsafe_b64encode(data).rstrip(b'=').decode()


def uint(n, size=None):
    raw = n.to_bytes((n.bit_length() + 7) // 8 if size is None else size, 'big')
    return b64(raw)


def jwk(kid, key):
    pub = key.public_key().public_numbers()
    if isinstance(key, rsa.RSAPrivateKey):
        return {'kty': 'RSA', 'kid': kid, 'use': 'sig', 'alg': 'RS256', 'n': uint(pub.n), 'e': uint(pub.e)}
    return {'kty': 'EC', 'kid': kid, 'use': 'sig', 'alg': 'ES256', 'crv': 'P-256', 'x': uint(pub.x, 32), 'y': uint(pub.y, 32)}


def sign(header, payload, key=None, secret=None):
    signing_input = (b64(json.dumps(header, separators=(',', ':')).encode()) + '.'
                     + b64(json.dumps(payload, separators=(',', ':')).encode())).encode()
    if header['alg'] == 'none':
        signature = b''
    elif secret is not None:
        signature = hmac.new(secret, signing_input, hashlib.sha256).digest()
    elif isinstance(key, rsa.RSAPrivateKey):
        signature = key.sign(signing_input, padding.PKCS1v15(), hashes.SHA256())
    else:
        r, s = decode_dss_signature(key.sign(signing_input, ec.ECDSA(hashes.SHA256())))
        signature = r.to_bytes(32, 'big') + s.to_bytes(32, 'big')
    return signing_input.decode() + '.' + b64(signature)


def claims(**changes):
    c = {'iss': ISSUER, 'aud': AUDIENCE, 'sub': 'user-1', 'preferred_username': 'fixture.user',
         'iat': FIXTURE_NOW - 60, 'nbf': FIXTURE_NOW - 60, 'exp': FIXTURE_NOW + 3600}
    for k, v in changes.items():
        if v is None:
            c.pop(k, None)
        else:
            c[k] = v
    return c


def main():
    rs1 = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    rs2 = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    es1 = ec.generate_private_key(ec.SECP256R1())
    jwks = {'keys': [jwk('rs-1', rs1), jwk('es-1', es1)]}
    rotated = {'keys': jwks['keys'] + [jwk('rs-2', rs2)]}
    rs_header = {'alg': 'RS256', 'typ': 'JWT', 'kid': 'rs-1'}
    public_pem = rs1.public_key().public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo)
    good = sign(rs_header, claims(), rs1)
    head, body, sig = good.split('.')
    flipped = sig[:-2] + ('A' if sig[-2] != 'A' else 'B') + sig[-1]

    tokens = [
        ('good-rs256', sign(rs_header, claims(), rs1), 'accept', 'signed by rs-1 with every required claim'),
        ('good-es256', sign({'alg': 'ES256', 'typ': 'JWT', 'kid': 'es-1'}, claims(), es1), 'accept', 'signed by es-1'),
        ('audience-in-array', sign(rs_header, claims(aud=['https://other.invalid', AUDIENCE]), rs1), 'accept', 'aud is an array holding the audience'),
        ('expired-within-skew', sign(rs_header, claims(exp=FIXTURE_NOW - 30), rs1), 'accept', 'exp 30 s ago, inside the 60 s skew'),
        ('expired', sign(rs_header, claims(exp=FIXTURE_NOW - 61), rs1), 'reject', 'exp 61 s ago'),
        ('not-yet-valid', sign(rs_header, claims(nbf=FIXTURE_NOW + 61), rs1), 'reject', 'nbf 61 s ahead'),
        ('missing-exp', sign(rs_header, claims(exp=None), rs1), 'reject', 'exp is required'),
        ('missing-nbf', sign(rs_header, claims(nbf=None), rs1), 'reject', 'nbf is required'),
        ('wrong-issuer', sign(rs_header, claims(iss='https://evil.invalid'), rs1), 'reject', 'iss differs'),
        ('wrong-audience', sign(rs_header, claims(aud='https://other.invalid'), rs1), 'reject', 'aud differs'),
        ('alg-none', sign({'alg': 'none', 'typ': 'JWT', 'kid': 'rs-1'}, claims()), 'reject', 'alg none is always rejected'),
        ('hs256-public-key', sign({'alg': 'HS256', 'typ': 'JWT', 'kid': 'rs-1'}, claims(), secret=public_pem), 'reject',
         'HMAC with the RSA public key as the secret'),
        ('bad-signature', head + '.' + body + '.' + flipped, 'reject', 'one signature character changed'),
        ('alg-key-mismatch', sign({'alg': 'ES256', 'typ': 'JWT', 'kid': 'rs-1'}, claims(), es1), 'reject', 'ES256 header naming an RSA key'),
        ('unknown-kid', sign({'alg': 'RS256', 'typ': 'JWT', 'kid': 'rs-2'}, claims(), rs2), 'refresh',
         'kid rs-2 is only in jwks-rotated.json: rejected until a refresh at least 30 s after the last fetch, then accepted'),
    ]
    out = {
        '_comment': HEADER,
        'now': FIXTURE_NOW,
        'issuer': ISSUER,
        'audience': AUDIENCE,
        'algorithms': ['RS256', 'ES256'],
        'skewSeconds': 60,
        'expectedClaims': {'sub': 'user-1', 'preferred_username': 'fixture.user'},
        'tokens': [{'name': n, 'token': t, 'expect': e, 'why': w} for n, t, e, w in tokens],
        'introspection': {
            'clientId': 'fixture-client',
            'responses': [
                {'name': 'active', 'opaque': 'opaque-active-0001', 'expect': 'accept',
                 'response': {'active': True, 'iss': ISSUER, 'aud': AUDIENCE, 'sub': 'user-1', 'preferred_username': 'fixture.user',
                              'token_type': 'access_token', 'exp': FIXTURE_NOW + 120}},
                {'name': 'revoked', 'opaque': 'opaque-revoked-0002', 'expect': 'reject', 'response': {'active': False}},
                {'name': 'expired', 'opaque': 'opaque-expired-0003', 'expect': 'reject',
                 'response': {'active': True, 'iss': ISSUER, 'sub': 'user-1', 'exp': FIXTURE_NOW - 61}},
                {'name': 'wrong-issuer', 'opaque': 'opaque-issuer-0004', 'expect': 'reject',
                 'response': {'active': True, 'iss': 'https://evil.invalid', 'sub': 'user-1', 'exp': FIXTURE_NOW + 120}},
                {'name': 'wrong-audience', 'opaque': 'opaque-audience-0005', 'expect': 'reject',
                 'response': {'active': True, 'iss': ISSUER, 'aud': 'https://other.invalid', 'sub': 'user-1', 'exp': FIXTURE_NOW + 120}},
            ],
        },
    }
    for name, value in (('jwks.json', dict(_comment=HEADER, **jwks)), ('jwks-rotated.json', dict(_comment=HEADER, **rotated)), ('tokens.json', out)):
        (HERE / name).write_text(json.dumps(value, indent=2) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
