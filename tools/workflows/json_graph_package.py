"""Materialize the installed generic JSON compiler factory from canonical contracts."""
import argparse
import json
from pathlib import Path
import tempfile
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.workflows.graph_package import build

DESTINATION = ROOT / 'apps/langgraph-runtime/src/toolgate_runtime/graphs'


def package(destination=DESTINATION, *, check=False):
    schema = json.loads((ROOT/'packages/contracts/schemas/v2/workflow.schema.json').read_text(encoding='utf-8'))
    names = ('WorkflowJsonGraph', 'WorkflowJsonNode', 'WorkflowJsonNodeKind', 'WorkflowJsonBranchRoutes', 'WorkflowJsonEdge', 'WorkflowAgentResultMode')
    definitions = {name:schema['$defs'][name] for name in (*names, 'WorkflowGraphSelection', 'WorkflowGraphBuildRequest', 'WorkflowGraphBuildResult', 'WorkflowGraphCandidate', 'WorkflowGraphCapabilities')}
    contract = ROOT/'apps/langgraph-runtime/src/toolgate_runtime/graph-runtime.schema.json'
    content = json.dumps({'$comment':'Copyright 2026 OLO Labs; SPDX-License-Identifier: Apache-2.0; generated by tools/workflows/json_graph_package.py','$defs':definitions},indent=2)+'\n'
    if check:
        if not contract.is_file() or contract.read_text(encoding='utf-8') != content:
            raise ValueError('Runtime graph contracts differ from canonical schemas')
    else:
        contract.write_text(content,encoding='utf-8')
    config_schema = {'$ref': '#/$defs/WorkflowJsonGraph', '$defs': {name:schema['$defs'][name] for name in names}}
    with tempfile.TemporaryDirectory() as temporary:
        source = Path(temporary)
        (source/'graph.py').write_text(
            '# Copyright 2026 OLO Labs; SPDX-License-Identifier: Apache-2.0\n'
            'from toolgate_runtime.json_graph import build_graph\n', encoding='utf-8')
        (source/'README.md').write_text(
            '# JSON workflow compiler\n\nInstalled implementation; topology and expressions are strict JSON. '
            'Run capabilities are injected at execution time. Unsupported features fail before activation.\n', encoding='utf-8')
        declaration = dict(format=1,packageId='olo.json-graph',version='1.0.0',runtimeApi=1,
            dependencies={'langgraph':'1.2.20'},capabilities=['json-state','agents','models','tools','async','branches','parallel-compute'],
            factories={'workflow':dict(file='graph.py',function='build_graph',configSchema=config_schema,outputSchema={})})
        (source/'package.json').write_text(json.dumps(declaration),encoding='utf-8')
        return build(source, destination, check=check)


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    print(json.dumps(package(check=args.check),indent=2))
