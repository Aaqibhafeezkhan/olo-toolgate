"""Generate the shared management permission vocabulary; no runtime legacy aliases."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'packages/contracts/management-permissions.json'


def catalog():
    result = json.loads(SOURCE.read_text(encoding='utf-8'))
    ids = [f"{r['id']}.{a}" for r in result['resources'] for a in r['actions']]
    if len(ids) != len(set(ids)):
        raise ValueError('Duplicate permission')
    if any(permission not in ids for requirements in result['routes'].values() for permission in requirements):
        raise ValueError('Unknown route capability')
    return result


def outputs():
    source = catalog()
    values = [f"{r['id']}.{a}" for r in source['resources'] for a in r['actions']]
    header = '// Copyright 2026 OLO Labs\n// SPDX-License-Identifier: Apache-2.0\n// GENERATED by tools/access/permissions.py; edit packages/contracts/management-permissions.json.\n'
    java = header + 'package io.ololabs.toolgate.control.application;\nimport java.util.*;\nimport io.ololabs.toolgate.control.domain.Ids.Kind;\npublic final class ManagementPermissionCatalog {\n private ManagementPermissionCatalog() {}\n public static final Set<String> ALL=Set.of(\n' + ',\n'.join('  '+json.dumps(v) for v in values) + ');\n public static String resource(Kind kind){return switch(kind){\n' + ''.join(f'  case {r["kind"]} -> "{r["id"]}";\n' for r in source['resources'] if 'kind' in r) + ' };}\n}\n'
    ts = header + 'export const managementCatalog = ' + json.dumps(source, indent=2) + ' as const;\nexport type ManagementPermission = ' + ' | '.join(json.dumps(v) for v in values) + ';\n'
    return {
        ROOT / 'apps/control-plane/src/main/java/io/ololabs/toolgate/control/application/ManagementPermissionCatalog.java': java,
        ROOT / 'apps/admin-ui/src/managementPermissions.generated.ts': ts,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    for path, content in outputs().items():
        if options.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Outdated permission vocabulary: {path.relative_to(ROOT)}')
        else:
            path.write_text(content, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
